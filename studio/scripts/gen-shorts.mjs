// Inline the Shorts scripts (../shorts/scripts.json) + measured voice durations into src/shorts/data.generated.ts.
// Timing: each line starts after the previous line's audio + its gap; LEAD frames of silence at the start.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FPS = 30, LEAD = 6, TAIL = 14;
const scripts = JSON.parse(fs.readFileSync(path.join(root, '../shorts/scripts.json'), 'utf8'));
const durations = JSON.parse(fs.readFileSync(path.join(root, 'public/audio/shorts/durations.json'), 'utf8'));
const out = scripts.shorts.map((s) => {
  let f = LEAD;
  const lines = s.lines.map((l) => {
    const dur = durations[l.id];
    if (!dur) throw new Error(`no audio for ${l.id}`);
    const len = Math.round(dur * FPS);
    const line = {id: l.id, text: l.text, from: f, len};
    f += len + Math.round((l.gap ?? 0.15) * FPS);
    return line;
  });
  return {id: s.id, title: s.title, music: s.music, lines, total: f + TAIL};
});
fs.mkdirSync(path.join(root, 'src/shorts'), {recursive: true});
fs.writeFileSync(path.join(root, 'src/shorts/data.generated.ts'),
  `// AUTO-GENERATED by scripts/gen-shorts.mjs — do not edit.\nimport type {ShortData} from './kit';\nexport const SHORTS: ShortData[] = ${JSON.stringify(out, null, 1)};\n`);
for (const s of out) console.log(`${s.id}: ${(s.total / FPS).toFixed(1)}s`);
